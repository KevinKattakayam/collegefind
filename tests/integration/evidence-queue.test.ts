import {beforeEach,it,expect,vi} from 'vitest';
import {testDb,resetDb} from './db';
import {evidenceQueue,queueQuery} from '@/server/evidence-queue';
const db=testDb();
vi.mock('@/lib/prisma',async()=>({prisma:(await import('./db')).testDb()}));
const auth=vi.hoisted(()=>({id:null as string|null}));
vi.mock('next-auth',()=>({getServerSession:async()=>auth.id?{user:{id:auth.id}}:null}));
const routes=await import('@/app/api/admin/evidence/route');
const identity=await import('@/app/api/admin/identity/route');
beforeEach(async()=>{await resetDb();auth.id=null;});
it('filters before paging, counts conflicts across page boundaries and keeps tied ordering stable',async()=>{
 const c=await db.college.create({data:{slug:'queue',name:'Queue',shortName:'Q',city:'X',state:'X',type:'PRIVATE'}});
 const src=await db.source.create({data:{name:'TEST',publisher:'TEST',url:'https://example.test',retrievedAt:new Date()}});
 for(let i=0;i<30;i++)await db.fieldEvidence.create({data:{id:'queue-'+String(i).padStart(2,'0'),collegeId:c.id,sourceId:src.id,field:'description',value:String(i),identityKey:String(i),createdAt:new Date('2026-01-01'),academicYear:2026}});
 const a=await evidenceQueue(db,{pageSize:10,status:'CONFLICT'});const b=await evidenceQueue(db,{pageSize:10,page:2,status:'CONFLICT'});
 expect(a.total).toBe(30);expect(a.items).toHaveLength(10);expect(b.items[0].id).toBe('queue-19');expect(new Set([...a.items,...b.items].map(c=>c.id)).size).toBe(20);
 expect(a.items[0].queueState).toBe('CONFLICTED');expect(a.items[0].conflicts.length).toBeGreaterThan(0);
 expect((await evidenceQueue(db,{q:'absent'})).total).toBe(0);
 expect((await evidenceQueue(db,{q:'queue-02',status:'CONFLICTED'})).items.map((item)=>item.id)).toEqual(['queue-02']);
 expect((await evidenceQueue(db,{page:10})).items).toEqual([]);
 expect(queueQuery.safeParse({page:0}).success).toBe(false);expect(queueQuery.safeParse({pageSize:101}).success).toBe(false);
 expect(queueQuery.safeParse({academicYear:''}).success).toBe(true);
 expect(queueQuery.safeParse({academicYear:'not-a-year'}).success).toBe(false);
 expect((await routes.GET(new Request('http://localhost/api/admin/evidence'))).status).toBe(401);
 const user=await db.user.create({data:{name:'User',email:'u@example.test',password:'fixture'}});auth.id=user.id;
 expect((await routes.GET(new Request('http://localhost/api/admin/evidence'))).status).toBe(403);
 await db.user.update({where:{id:user.id},data:{role:'ADMIN'}});
 expect((await routes.GET(new Request('http://localhost/api/admin/evidence?pageSize=101'))).status).toBe(400);
 expect((await routes.GET(new Request('http://localhost/api/admin/evidence?status=CONFLICT'))).status).toBe(200);
 await db.institutionAlias.create({data:{collegeId:c.id,namespace:'NAME',value:'Old Queue',campus:'main',sourceUrl:src.url,validUntil:new Date('2020-01-01')}});
 const filtered=await evidenceQueue(db,{status:'CONFLICTED',college:'queue',campus:'main',field:'descrip',academicYear:2026,freshness:'SOURCE_UNDATED'});
 expect(filtered.total).toBe(30);expect(filtered.items[0].conflicts.length).toBeGreaterThan(0);
 const resolved=await identity.GET(new Request('http://localhost/api/admin/identity?namespace=NAME&value=Old%20Queue&campus=main'));
 expect((await resolved.json()).status).toBe('UNMATCHED');
 const body={collegeId:c.id,namespace:'AISHE',value:'TEST-ALIAS',campus:'main',sourceUrl:'https://example.test',reason:'Synthetic alias test'};
 const write=()=>identity.POST(new Request('http://localhost/api/admin/identity',{method:'POST',headers:{origin:'http://localhost','content-type':'application/json'},body:JSON.stringify(body)}));
 expect((await write()).status).toBe(200);
 expect(await db.auditLog.count({where:{action:'identity.reconcile'}})).toBe(1);
 auth.id=null;expect((await write()).status).toBe(401);
 expect((await identity.GET(new Request('http://localhost/api/admin/identity?namespace=NAME&value=Old&campus=main'))).status).toBe(401);
});
